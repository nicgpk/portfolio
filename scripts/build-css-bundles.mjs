import {readFileSync, writeFileSync, mkdirSync, existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

// Keep source stylesheets editable and preserve their exact cascade order.
// Outputs remain in css/, so relative font and image URLs do not need rewriting.
const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const outputs = new Map();
// Git checks text out with platform-specific newlines. Hash the canonical LF
// content so generated URLs and verification agree on Windows and Linux.
const readOnDisk = file => readFileSync(path.join(root, file), 'utf8').replaceAll('\r\n', '\n');
const read = file => outputs.get(file) ?? readOnDisk(file);
const hash = text => createHash('sha256').update(text).digest('hex').slice(0, 12);
const stripVersion = url => url.split(/[?#]/, 1)[0];
const bundles = {
  'shared-base': ['folio', 'editorial', 'studio'],
  'home-layout': ['project-system', 'personal-landing', 'link-system', 'craft-motion'],
  'home-product': ['work-index', 'product-surfaces', 'two-tone'],
  'case-layout': ['concepts', 'project-system', 'personal-landing', 'case-studies', 'link-system', 'evidence-motion', 'craft-motion'],
  'case-product': ['case-refined', 'product-surfaces'],
  'growth-product': ['case-growth', 'two-tone'],
  'discount-product': ['case-discount', 'two-tone'],
  'developer-concepts': ['vesper-tokens', 'vesper-concepts'],
  'developer-product': ['case-developer', 'two-tone'],
  'resume-layout': ['teletype', 'resume', 'folio', 'studio', 'link-system', 'resume-portfolio', 'vesper-tokens'],
};
const routes = {
  'index.html': ['shared-base', 'home-layout', 'glass', 'home-product'],
  'partner-growth-programs.html': ['shared-base', 'case-layout', 'glass', 'case-product', 'growth-product'],
  'discounting.html': ['shared-base', 'case-layout', 'glass', 'case-product', 'discount-product'],
  'dev-portal.html': ['shared-base', 'case-layout', 'developer-concepts', 'glass', 'case-product', 'developer-product'],
  'resume.html': ['resume-layout', 'glass'],
};
const removed = {
  'partner-growth-programs.html': ['growth-ui', 'vesper-tokens', 'vesper-concepts'],
  'discounting.html': ['discount-ui', 'vesper-tokens', 'vesper-concepts'],
};

// Fail rather than silently omit CSS if a removed product root is reintroduced.
for (const [file, roots] of Object.entries({
  'partner-growth-programs.html': ['growth-studio', 'growth-workspace-title', 'growth-property', 'program-label-open', 'program-label-closed', 'program-tile', 'lifecycle-playbook', 'lifecycle-pattern', 'concept-shell', 'concept-preview'],
  'discounting.html': ['discount-studio', 'concept-shell', 'concept-preview'],
})) {
  const html = read(file);
  const classes = new Set([...html.matchAll(/\bclass\s*=\s*['"]([^'"]+)['"]/g)]
    .flatMap(match => match[1].split(/\s+/)));
  for (const name of roots) {
    if (classes.has(name)) throw new Error(`${file}: restore styles for the reintroduced .${name} root.`);
  }
  if (/\bdata-vesper-theme\s*=/.test(html)) throw new Error(`${file}: a Vesper theme needs its source styles.`);
}

const dependencies = new Set();
function source(file) {
  dependencies.add(file);
  let css = read(file);
  if (/@(?:charset|namespace)\b/i.test(css)) throw new Error(`${file}: handle its stylesheet-level directive before bundling.`);
  if (/@import\b/i.test(css)) {
    const importedMotion = /^@import url\(['"]motion\.css\?v=7['"]\);/;
    if (file !== 'css/teletype.css' || !importedMotion.test(css)) {
      throw new Error(`${file}: an unhandled CSS import would change the cascade.`);
    }
    // This import precedes every rule in teletype.css. Inline it at that exact point.
    css = css.replace(importedMotion, () => source('css/motion.css'));
    if (/@import\b/i.test(css)) throw new Error(`${file}: unexpected additional CSS import.`);
  }
  return `/* Source: ${file} */\n${css}\n`;
}

const manifest = {bundles: {}, shared: {}, routes: {}};
for (const [name, names] of Object.entries(bundles)) {
  const files = names.map(name => `css/${name}.css`);
  const text = ('/* Generated by scripts/build-css-bundles.mjs; edit the source stylesheets. */\n'
    + files.map(source).join('\n')).trimEnd() + '\n';
  const file = `css/bundle-${name}.css`;
  const href = `${file}?v=${hash(text)}`;
  outputs.set(file, text);
  manifest.bundles[name] = {file, href, sources: files, bytes: Buffer.byteLength(text)};
}
manifest.shared.glass = `css/glass.css?v=${hash(read('css/glass.css'))}`;
// Only these wave dependencies changed with this optimization. Version their
// imports in dependency order so returning visitors cannot mix old and new APIs.
const shaderMountHash = hash(read('js/vendor/paper/shader-mount.js'));
for (const file of ['js/paper-wave.mjs', 'js/wave-noise-cache.mjs']) {
  let count = 0;
  const updated = read(file).replace(/(['"])((?:\.\.?\/)+vendor\/paper\/shader-mount\.js)(?:\?[^'"]*)?\1/g,
    (_, quote, specifier) => { count++; return `${quote}${specifier}?v=${shaderMountHash}${quote}`; });
  if (count !== 1) throw new Error(`${file}: expected exactly one ShaderMount import.`);
  outputs.set(file, updated);
}
const noiseCacheHash = hash(read('js/wave-noise-cache.mjs'));
let cacheImports = 0;
outputs.set('js/paper-wave.mjs', read('js/paper-wave.mjs').replace(
  /(['"])((?:\.\.?\/)+wave-noise-cache\.mjs)(?:\?[^'"]*)?\1/g,
  (_, quote, specifier) => { cacheImports++; return `${quote}${specifier}?v=${noiseCacheHash}${quote}`; },
));
if (cacheImports !== 1) throw new Error('js/paper-wave.mjs: expected exactly one noise-cache import.');
manifest.shared['shader-mount'] = `js/vendor/paper/shader-mount.js?v=${shaderMountHash}`;
manifest.shared['wave-noise-cache'] = `js/wave-noise-cache.mjs?v=${noiseCacheHash}`;
for (const name of ['paper-wave', 'glass-demos']) {
  const file = `js/${name}.mjs`;
  manifest.shared[name] = `${file}?v=${hash(read(file))}`;
}

const stylesheet = /^[\t ]*<link\b(?=[^>]*\brel\s*=\s*['"]stylesheet['"])[^>]*>[\t ]*(?:\r?\n|$)/gm;
const marker = /[\t ]*<!-- css-bundles:start -->[\s\S]*?<!-- css-bundles:end -->\r?\n?/;
const getHref = tag => tag.match(/\bhref\s*=\s*['"]([^'"]+)['"]/)?.[1];
for (const [file, sequence] of Object.entries(routes)) {
  let html = read(file);
  const newline = html.includes('\r\n') ? '\r\n' : '\n';
  const hrefs = sequence.map(name => name === 'glass' ? manifest.shared.glass : manifest.bundles[name].href);
  const tags = [...html.matchAll(stylesheet)].map(match => match[0]);
  if (tags.some(tag => /\b(?:media|disabled|title|integrity)\s*=/.test(tag))) {
    throw new Error(`${file}: preserve stylesheet attributes explicitly before bundling.`);
  }
  if (marker.test(html)) {
    const actual = tags.map(getHref).map(stripVersion);
    if (JSON.stringify(actual) !== JSON.stringify(hrefs.map(stripVersion))) {
      throw new Error(`${file}: update the bundle manifest for the changed stylesheet links.`);
    }
  } else {
    const expected = sequence.flatMap(name => name === 'glass' ? ['css/glass.css'] : manifest.bundles[name].sources);
    const actual = tags.map(getHref).map(stripVersion)
      .filter(fileName => !(removed[file] ?? []).some(name => fileName === `css/${name}.css`));
    if (JSON.stringify(actual) !== JSON.stringify(expected)) {
      throw new Error(`${file}: source stylesheet order differs from its bundle manifest.`);
    }
  }
  const block = [
    '    <!-- css-bundles:start -->',
    ...hrefs.map(href => `    <link rel="stylesheet" href="${href}" />`),
    '    <!-- css-bundles:end -->',
    '',
  ].join(newline);
  if (marker.test(html)) html = html.replace(marker, block);
  else {
    let first = true;
    html = html.replace(stylesheet, () => {
      if (!first) return '';
      first = false;
      return block;
    });
  }
  for (const name of ['paper-wave', 'glass-demos']) {
    const filename = new RegExp(`js/${name}\\.mjs(?:\\?[^'"\\s<]*)?`, 'g');
    html = html.replace(filename, manifest.shared[name]);
  }
  // Identical font preloads are coalesced by browsers; keep just one declaration.
  const preloaded = new Set();
  html = html.replace(/^[\t ]*<link\b(?=[^>]*\brel\s*=\s*['"]preload['"])(?=[^>]*\bas\s*=\s*['"]font['"])[^>]*>[\t ]*\r?\n?/gm, tag => {
    const href = getHref(tag);
    if (preloaded.has(href)) return '';
    preloaded.add(href);
    return tag;
  });
  outputs.set(file, html);
  manifest.routes[file] = {stylesheets: hrefs, count: hrefs.length};
}
manifest.sourceDependencies = [...dependencies].sort();
outputs.set('css/bundles.manifest.json', `${JSON.stringify(manifest, null, 2)}\n`);

let stale = false;
for (const [file, content] of outputs) {
  if (existsSync(path.join(root, file)) && readOnDisk(file) === content) continue;
  if (check) {
    console.error(`Stale CSS build: ${file}`);
    stale = true;
  } else {
    mkdirSync(path.dirname(path.join(root, file)), {recursive: true});
    writeFileSync(path.join(root, file), content);
  }
}
if (stale) {
  console.error('Run node scripts/build-css-bundles.mjs after changing source styles or shared entry modules.');
  process.exitCode = 1;
} else {
  console.log(`${check ? 'Verified' : 'Built'} ${Object.keys(bundles).length} ordered CSS bundles for ${Object.keys(routes).length} routes.`);
  for (const [file, {count}] of Object.entries(manifest.routes)) console.log(`${file}: ${count} stylesheet requests`);
}
